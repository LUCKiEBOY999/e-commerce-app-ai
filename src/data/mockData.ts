const R: any = results;

const applyRealStats = (target: ClusterInfo[], k: number) => {
  const real = R.byK[String(k)]?.clusters;
  if (!real) return;
  target.forEach((c) => {
    const r = real.find((x: any) => x.id === c.id);
    if (!r) return;
    c.productCount = r.productCount;
    c.percentage = r.percentage;
    c.avgPrice = r.avgPrice;
    c.avgDiscount = r.avgDiscount;
    c.avgQuantitySold = r.avgQuantitySold;
    c.avgSalesValue = r.avgSalesValue;
  });
};

applyRealStats(CLUSTERS, R.defaultK);
Object.keys(CLUSTERS_BY_K).forEach((k) => applyRealStats(CLUSTERS_BY_K[Number(k)], Number(k)));

const rateSil = (v: number) =>
  v >= 0.5 ? { th: 'ดี (Good)', en: 'Good Separation' }
  : v >= 0.25 ? { th: 'ปานกลาง (Fair - โครงสร้างกลุ่มไม่ชัดมาก)', en: 'Fair Separation (weak structure)' }
  : { th: 'อ่อน (Poor)', en: 'Poor Separation' };
const rateDb = (v: number) =>
  v <= 1.0 ? { th: 'ดี (Good)', en: 'Good' }
  : v <= 1.5 ? { th: 'ปานกลาง (Moderate)', en: 'Moderate' }
  : { th: 'อ่อน (Weak)', en: 'Weak' };

// K_METRICS + ELBOW_DATA: ใช้ค่าจากโมเดลที่ fit กับข้อมูลทั้งชุดทุกค่า K
Object.keys(R.byK).forEach((key) => {
  const k = Number(key);
  const m = R.byK[key];
  const sr = rateSil(m.silhouette);
  const dr = rateDb(m.daviesBouldin);
  K_METRICS[k] = {
    silhouetteScore: m.silhouette,
    silRatingTh: sr.th,
    silRatingEn: sr.en,
    dbIndex: m.daviesBouldin,
    dbRatingTh: dr.th,
    dbRatingEn: dr.en,
    inertia: m.inertia,
    iterations: m.nIter,
  };
});
